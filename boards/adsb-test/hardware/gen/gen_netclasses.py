#!/usr/bin/env python3
"""Net classes (impedance-controlled nets) and pair-matching DRC rules for ADSB_Test.

Run from the repo root:  python boards/adsb-test/hardware/gen/gen_netclasses.py
Writes net_settings into ADSB_Test.kicad_pro and the custom rules file ADSB_Test.kicad_dru.

Differential pairs are recognised by KiCad from the _P/_N (or P/N) name suffix, so USB pairs
are named *_D_P / *_D_N, MIPI DSI_*_P / *_N, Ethernet ETH_TXP/TXN, ETH_RXP/RXN.
Widths/gaps are STARTING VALUES for a 4-layer 1.6 mm board with ~0.2 mm prepreg to the L2 ground:
recalculate them with PCBWay's stack-up / impedance calculator before layout (docs/pcb-manufacturing.md).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
KICAD = ROOT / "boards/adsb-test/hardware/kicad"


def nc(name, track, clearance, dp_w=None, dp_gap=None, colour="rgba(0, 0, 0, 0.000)", prio=0):
    c = {"name": name, "priority": prio, "clearance": clearance, "track_width": track,
         "via_diameter": 0.6, "via_drill": 0.3, "microvia_diameter": 0.3, "microvia_drill": 0.1,
         "diff_pair_width": dp_w or track, "diff_pair_gap": dp_gap or clearance, "diff_pair_via_gap": 0.25,
         "wire_width": 6, "bus_width": 12, "line_style": 0, "schematic_color": colour,
         "pcb_color": "rgba(0, 0, 0, 0.000)", "tuning_profile": ""}
    return c


CLASSES = [
    nc("Default", 0.15, 0.15, prio=2147483647),
    nc("USB_90R", 0.20, 0.15, 0.20, 0.15, "rgb(0, 102, 204)", 1),      # USB 2.0 HS, 90 ohm differential
    nc("MIPI_100R", 0.15, 0.15, 0.15, 0.20, "rgb(170, 0, 170)", 2),    # MIPI-DSI, 100 ohm differential
    nc("ETH_100R", 0.15, 0.15, 0.15, 0.20, "rgb(210, 105, 0)", 3),     # 10/100 Ethernet MDI, 100 ohm differential
    nc("RF_50R", 0.35, 0.20, colour="rgb(200, 0, 0)", prio=4),       # 50 ohm CPW to the SMAs (gap = CPW gap)
]
PATTERNS = [
    ("USB_90R", "*_D_P"), ("USB_90R", "*_D_N"),
    ("MIPI_100R", "*DSI_*"),
    ("ETH_100R", "*ETH_TX?"), ("ETH_100R", "*ETH_RX?"),
    ("RF_50R", "*RF_ADSB_ANT"), ("RF_50R", "*M1421_RF_*"), ("RF_50R", "*GPS_RF"), ("RF_50R", "*WIFI_ANT"),
]

pro = KICAD / "ADSB_Test.kicad_pro"
d = json.loads(pro.read_text(encoding="utf-8"))
ns = d.setdefault("net_settings", {})
ns["classes"] = CLASSES
ns["netclass_patterns"] = [{"netclass": c, "pattern": p} for c, p in PATTERNS]
ns["meta"] = {"version": 4}
pro.write_text(json.dumps(d, indent=2) + "\n", encoding="utf-8", newline="\n")

DRU = """(version 1)
# ADSB_Test custom design rules (generated by hardware/gen/gen_netclasses.py).
# Pair widths/gaps come from the net classes; recalculate them for PCBWay's stack-up before layout.

# USB 2.0 HS (90R): each pair matched to 0.15 mm, uncoupled length kept short
(rule "USB pair skew"
  (condition "A.NetClass == 'USB_90R'")
  (constraint skew (max 0.15mm) (within_diff_pairs))
  (constraint diff_pair_uncoupled (max 3mm)))

# MIPI-DSI (100R): each pair matched to 0.1 mm, and the clock + 2 data lanes matched to 1 mm
(rule "DSI pair skew"
  (condition "A.NetClass == 'MIPI_100R'")
  (constraint skew (max 0.1mm) (within_diff_pairs))
  (constraint diff_pair_uncoupled (max 2mm)))
(rule "DSI lane matching"
  (condition "A.NetClass == 'MIPI_100R'")
  (constraint skew (max 1mm)))

# Ethernet MDI (100R) between the PHY and the MagJack: each pair matched to 0.5 mm
(rule "Ethernet pair skew"
  (condition "A.NetClass == 'ETH_100R'")
  (constraint skew (max 0.5mm) (within_diff_pairs)))

# RF 50R: keep vias off the RF feeds (ground-via fence is fine)
(rule "RF no vias"
  (condition "A.NetClass == 'RF_50R'")
  (constraint via_count (max 0)))
"""
(KICAD / "ADSB_Test.kicad_dru").write_text(DRU, encoding="utf-8", newline="\n")
print("net classes:", ", ".join(c["name"] for c in CLASSES), "| rules: ADSB_Test.kicad_dru")
