#!/usr/bin/env python3
"""Net classes (impedance-controlled nets) and pair-matching DRC rules for ADSB_Test.

Run from the repo root:  python boards/adsb-test/hardware/gen/gen_netclasses.py
Writes net_settings into ADSB_Test.kicad_pro and the custom rules file ADSB_Test.kicad_dru.

Differential pairs are recognised by KiCad from the _P/_N (or P/N) name suffix, so USB pairs
are named *_D_P / *_D_N, MIPI DSI_*_P / *_N, Ethernet ETH_TX_P/_N, ETH_RX_P/_N.
Widths/gaps are for PCBWay's standard 4-layer 1.6 mm stack-up (outer layer over 0.1855 mm 7628 prepreg,
Dk 4.74, 1 oz; stack-up written into the board by gen_pcb.py), from tools/impedance.py (IPC-2141 / CPWG closed
forms, about +-10 %). Order impedance control: PCBWay trims the widths to hit the targets.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
KICAD = ROOT / "boards/adsb-test/hardware/kicad"


def nc(name, track, clearance, dp_w=None, dp_gap=None, colour="rgba(0, 0, 0, 0.000)", prio=0):
    c = {"name": name, "priority": prio, "clearance": clearance, "track_width": track,
         "via_diameter": 0.6, "via_drill": 0.3, "microvia_diameter": 0.3, "microvia_drill": 0.1,
         "diff_pair_width": dp_w or track, "diff_pair_gap": dp_gap or clearance, "diff_pair_via_gap": 0.25,
         "wire_width": 6, "bus_width": 12, "line_style": 0, "schematic_color": colour,
         "pcb_color": "rgba(0, 0, 0, 0.000)", "tuning_profile": ""}
    return c


CLASSES = [
    nc("Default", 0.15, 0.15, prio=2147483647),
    nc("USB_90R", 0.22, 0.15, 0.22, 0.15, "rgb(0, 102, 204)", 1),      # USB 2.0 HS, 90 ohm diff (W 0.22 / S 0.15)
    nc("MIPI_100R", 0.18, 0.15, 0.18, 0.15, "rgb(170, 0, 170)", 2),    # MIPI-DSI, 100 ohm diff (W 0.18 / S 0.15)
    nc("ETH_100R", 0.18, 0.15, 0.18, 0.15, "rgb(210, 105, 0)", 3),     # Ethernet MDI, 100 ohm diff (W 0.18 / S 0.15)
    nc("RF_50R", 0.32, 0.20, colour="rgb(200, 0, 0)", prio=4),       # 50 ohm CPWG: W 0.32, gap 0.20 to ground pour
    # Power. PWR_HI = charger / input / VSYS / buck outputs and every switch node: route BY HAND (short, wide,
    # pours where it helps) and leave them out of Freerouting. 0.8 mm on 1 oz outer is ~2 A for a 10 C rise.
    # PWR = the other rails, autorouted at 0.3 mm (still fits between 0.4 mm-pitch QFN pins); widen by hand where
    # a branch carries more than ~0.5 A. GND = the plane/fills and the ground vias from gen_pcb.py: never routed.
    nc("PWR_HI", 0.8, 0.2, colour="rgb(220, 0, 0)", prio=5),
    nc("PWR", 0.3, 0.15, colour="rgb(230, 120, 0)", prio=6),
    nc("GND", 0.3, 0.15, colour="rgb(0, 140, 0)", prio=7),
]
PWR_HI = ["VBUS_USER_RAW", "VBUS_USER", "VBUS_CHG", "*CHG_PMID", "*CHG_SW1", "*CHG_SW2", "*VSYS_CHG", "*VBAT_CHG",
          "BAT_PACK", "VSYS", "5V", "3V3_BUCK", "*B5V_SW", "*B3V3_SW", "*AVDD_SW", "*BL_SW"]
PWR = ["3V3", "3V3_DEV", "3V3_ETH", "3V3_GPS", "3V3_M1421", "3V3_MCU", "3V3_PERIPH", "3V3_SD", "*/3V3_*_SH",
       "5V_LCD", "5V_SDR", "*/5V_LCD_SH", "VBUS_DEV", "VBUS_HOST", "VBACKUP", "*VBACKUP_LDO",
       "*ETH_AVDD", "*ETH_1V2", "*FT_1V8", "*VCC_1V8", "*/AVDD", "*/VGH", "*/VGL", "*/VCOM", "*SD_VDD",
       "*CP_VBUS", "*LED_VDD"]
PATTERNS = [("GND", "GND")] + [("PWR_HI", p) for p in PWR_HI] + [("PWR", p) for p in PWR] + [
    ("USB_90R", "*_D_P"), ("USB_90R", "*_D_N"),
    ("MIPI_100R", "*DSI_*"),
    ("ETH_100R", "*ETH_TX_?"), ("ETH_100R", "*ETH_RX_?"),
    ("RF_50R", "*RF_ADSB_ANT"), ("RF_50R", "*M1421_RF_*"), ("RF_50R", "*GPS_RF"), ("RF_50R", "*WIFI_ANT"),
]

pro = KICAD / "ADSB_Test.kicad_pro"
d = json.loads(pro.read_text(encoding="utf-8"))
ns = d.setdefault("net_settings", {})
ns["classes"] = CLASSES
ns["netclass_patterns"] = [{"netclass": c, "pattern": p} for c, p in PATTERNS]
ns["meta"] = {"version": 4}
pro.write_text(json.dumps(d, indent=2) + "\n", encoding="utf-8", newline="\n")

DRU = """(version 1)
# ADSB_Test custom design rules (generated by hardware/gen/gen_netclasses.py).
# Pair widths/gaps come from the net classes; recalculate them for PCBWay's stack-up before layout.

# USB 2.0 HS (90R): each pair matched to 0.15 mm, uncoupled length kept short
(rule "USB pair skew"
  (condition "A.NetClass == 'USB_90R'")
  (constraint skew (max 0.15mm) (within_diff_pairs))
  (constraint diff_pair_uncoupled (max 3mm)))

# MIPI-DSI (100R): each pair matched to 0.1 mm, and the clock + 2 data lanes matched to 1 mm
(rule "DSI pair skew"
  (condition "A.NetClass == 'MIPI_100R'")
  (constraint skew (max 0.1mm) (within_diff_pairs))
  (constraint diff_pair_uncoupled (max 2mm)))
(rule "DSI lane matching"
  (condition "A.NetClass == 'MIPI_100R'")
  (constraint skew (max 1mm)))

# Ethernet MDI (100R) between the PHY and the MagJack: each pair matched to 0.5 mm
(rule "Ethernet pair skew"
  (condition "A.NetClass == 'ETH_100R'")
  (constraint skew (max 0.5mm) (within_diff_pairs)))

# RF 50R: keep vias off the RF feeds (ground-via fence is fine)
(rule "RF no vias"
  (condition "A.NetClass == 'RF_50R'")
  (constraint via_count (max 0)))

# Power: no track narrower than the class width except where it has to neck down into a fine-pitch pad
(rule "PWR_HI min width"
  (condition "A.NetClass == 'PWR_HI'")
  (constraint track_width (min 0.3mm) (opt 0.8mm)))

# Ground pads boxed in by neighbours (USB-C end pins; plated holes in the exposed pads of U1101 / U1401): one
# thermal spoke is enough, the pad is also tied to ground through the shell / its own exposed pad.
(rule "Tight ground pads: one spoke"
  (condition "A.memberOfFootprint('J901') || A.memberOfFootprint('J1001') || A.memberOfFootprint('U1101') || A.memberOfFootprint('U1401')")
  (constraint min_resolved_spokes 1))

# Edge-mount RP-SMA J602: Molex's pads run to the board edge; ours stop 0.25 mm short (PCBWay pull-back)
(rule "J602 pads to the edge"
  (condition "A.memberOfFootprint('J602') || B.memberOfFootprint('J602')")
  (constraint edge_clearance (min 0.2mm)))
"""
(KICAD / "ADSB_Test.kicad_dru").write_text(DRU, encoding="utf-8", newline="\n")
print("net classes:", ", ".join(c["name"] for c in CLASSES), "| rules: ADSB_Test.kicad_dru")
